"""Render the checked combat payload family from the canonical JSON Schema."""

from __future__ import annotations

import json
import re

COMBAT_PAYLOADS = {
    "combat_command": "CombatCommandEnvelope",
    "combat_state_request": "combatStateRequestData",
    "combat_state": "combatStateData",
    "action_result": "actionResultData",
    "action_rejected": "actionRejectedData",
}


def _name(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", value):
        raise ValueError(f"Unsupported schema definition name: {value}")
    return value[0].upper() + value[1:]


def _references(value):
    if isinstance(value, dict):
        if "$ref" in value:
            reference = value["$ref"]
            if not reference.startswith("#/$defs/"):
                raise ValueError(f"Unsupported payload reference: {reference}")
            yield reference.removeprefix("#/$defs/")
        for child in value.values():
            yield from _references(child)
    elif isinstance(value, list):
        for child in value:
            yield from _references(child)


def _type(schema: dict) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return _name(schema["$ref"].removeprefix("#/$defs/"))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for operator in ("anyOf", "oneOf"):
        if operator in schema:
            return " | ".join(dict.fromkeys(_type(child) for child in schema[operator]))
    kind = schema.get("type")
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        return "number"
    if kind == "array":
        return "Array<" + _type(schema.get("items", {})) + ">"
    if kind == "object":
        properties = schema.get("properties", {})
        additional = schema.get("additionalProperties", True)
        if not properties:
            return "Record<string, " + (_type(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = set(schema.get("required", []))
        fields = [json.dumps(key) + ("" if key in required else "?") + ": " + _type(value) + ";"
                  for key, value in properties.items()]
        if additional is not False:
            fields.append("[key: string]: " + (_type(additional) if isinstance(additional, dict) else "unknown") + ";")
        return "{\n" + "\n".join("  " + line.replace("\n", "\n  ") for line in fields) + "\n}"
    raise ValueError(f"Unsupported combat payload schema: {schema}")


def combat_payload_types(schema: dict, *, newline: str = "\n") -> bytes:
    """Fail if mappings drift; follow only the explicitly supported family."""
    if newline not in {"\n", "\r\n"}:
        raise ValueError("Unsupported generated-file line ending")
    definitions = schema["$defs"]
    for wire_type, definition in COMBAT_PAYLOADS.items():
        references = [rule.get("then", {}).get("properties", {}).get("data", {}).get("$ref")
                      for rule in schema["allOf"]
                      if rule.get("if", {}).get("properties", {}).get("type", {}).get("const") == wire_type]
        if references != [f"#/$defs/{definition}"]:
            raise ValueError(f"Combat payload mapping changed: {wire_type}")
    needed = set(COMBAT_PAYLOADS.values())
    pending = list(needed)
    while pending:
        for reference in _references(definitions[pending.pop()]):
            if reference not in needed:
                needed.add(reference)
                pending.append(reference)
    names = [_name(key) for key in needed]
    if len(set(names)) != len(names):
        raise ValueError("Combat payload type names collide")
    lines = ["// Generated by packages/core-table/scripts/generate_protocol_types.py. Do not edit.",
             "import type { Message } from './message';", ""]
    for key in sorted(needed):
        lines.extend([f"export type {_name(key)} = {_type(definitions[key])};", ""])
    lines.append("export interface CombatPayloads {")
    lines.extend(f"  {json.dumps(kind)}: {_name(definition)};" for kind, definition in COMBAT_PAYLOADS.items())
    lines.extend(["}", "", "export type CombatMessageType = keyof CombatPayloads;",
        "export type CombatMessage<K extends CombatMessageType = CombatMessageType> =",
        "  K extends CombatMessageType ? Omit<Message, 'type' | 'data'> & { type: K; data: CombatPayloads[K] } : never;", ""])
    return "\n".join(lines).replace("\n", newline).encode("utf-8")
